import { useCallback, useEffect, useState } from 'react';
import { BrainCircuit, ListChecks, CircleCheck, ShieldCheck, AlertCircle } from 'lucide-react';
import { request } from '../api.js';
import { useApp } from '../context/AppContext.jsx';

export default function Agent() {
  const { user, openModal, notify } = useApp();
  const [tasks, setTasks] = useState([]);
  const [summary, setSummary] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  const loadTasks = useCallback(async () => {
    if (!user) return;
    setBusy(true);
    setError('');
    try {
      const d = await request('/ai/agent/tasks');
      setTasks(d.tasks || []);
      setSummary(d.summary || null);
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }, [user]);

  useEffect(() => { loadTasks(); }, [loadTasks]);

  async function runAgent() {
    setBusy(true);
    setError('');
    try {
      const d = await request('/ai/agent/plan', { method: 'POST', body: JSON.stringify({}) });
      notify(d.message || 'Agent plan refreshed.');
      const fresh = await request('/ai/agent/tasks');
      setTasks(fresh.tasks || []);
      setSummary(fresh.summary || null);
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  }

  async function updateTask(id, status) {
    try {
      await request(`/ai/agent/tasks/${id}`, { method: 'PATCH', body: JSON.stringify({ status }) });
      const d = await request('/ai/agent/tasks');
      setTasks(d.tasks || []);
      setSummary(d.summary || null);
    } catch (e) {
      setError(e.message);
    }
  }

  return (
    <section className="agent-page">
      <div className="eyebrow"><BrainCircuit size={14} /> TRACEMATE AGENT WORKSPACE</div>
      <h1>What needs your attention?</h1>
      <p className="page-lead">The agent reviews your saved reports and claims, creates a persistent action plan, and lets you review each step. It never approves claims or marks belongings returned automatically.</p>

      <div className="agent-summary-grid four">
        <div className="agent-summary-card"><span>Pending actions</span><strong>{summary?.pendingTasks ?? '—'}</strong></div>
        <div className="agent-summary-card"><span>Your open reports</span><strong>{summary?.openOwnReports ?? '—'}</strong></div>
        <div className="agent-summary-card"><span>Claims to review</span><strong>{summary?.claimsToReview ?? '—'}</strong></div>
        <div className="agent-summary-card"><span>Your pending claims</span><strong>{summary?.pendingClaims ?? '—'}</strong></div>
      </div>

      <div className="agent-toolbar">
        <div><h2>Agent action plan</h2><p>Actions are generated from live MongoDB records for your account.</p></div>
        <button className="button button-primary" disabled={busy || !user} onClick={runAgent}>
          <BrainCircuit size={16} />{busy ? 'Reviewing records…' : 'Run agent & find pending work'}
        </button>
      </div>

      {!user && (
        <div className="api-warning">
          <AlertCircle size={17} /><span>Sign in to let the agent review your reports and claims.</span>
          <button onClick={() => openModal('auth')}>Sign in</button>
        </div>
      )}
      {error && <div className="form-error">{error}</div>}

      {!tasks.length ? (
        <div className="empty-state">
          <ListChecks size={30} /><h3>No agent tasks yet</h3>
          <p>Sign in, then run the agent. It inspects your reports and claims and creates review tasks.</p>
          <button className="button button-outline" disabled={!user || busy} onClick={loadTasks}>Load existing tasks</button>
        </div>
      ) : (
        <div className="agent-task-list">
          {tasks.map((task) => (
            <article className="agent-task-card" key={task._id}>
              <div className="agent-task-head">
                <span className={`priority-pill ${task.priority}`}>{task.priority} priority</span>
                <span className={`status-pill ${task.status}`}>{task.status}</span>
              </div>
              <h3>{task.title}</h3>
              <p>{task.description}</p>
              <small>{task.kind?.replaceAll('-', ' ')} · {task.generatedByAgent ? 'Generated by TraceMate agent' : 'Manual task'}</small>
              <div className="agent-task-actions">
                {task.status !== 'completed' && <button className="button button-primary" onClick={() => updateTask(task._id, 'completed')}><CircleCheck size={15} /> Mark complete</button>}
                {task.status === 'pending' && <button className="button button-outline" onClick={() => updateTask(task._id, 'dismissed')}>Dismiss</button>}
                {task.status !== 'pending' && <button className="button button-outline" onClick={() => updateTask(task._id, 'pending')}>Reopen</button>}
              </div>
            </article>
          ))}
        </div>
      )}
      <div className="privacy-note"><ShieldCheck size={16} /><span>Agentic behaviour: inspect live records → prioritize issues → save tasks to MongoDB → wait for your decision. Matching scores are heuristic suggestions, not proof of ownership.</span></div>
    </section>
  );
}
